// Compact builders keep the content tables readable.
SortItem _e(
  String id,
  String emoji,
  String name,
  String cat, {
  int lvl = 1,
  double scale = 1,
  EmojiEffect fx = EmojiEffect.none,
  String? fact,
  String? group,
  String? badge,
}) => SortItem(
  id: id,
  name: name,
  visual: EmojiVisual(emoji, scale: scale, effect: fx, badge: badge),
  categoryId: cat,
  minLevel: lvl,
  fact: fact,
  group: group,
);

SortItem _v(
  String id,
  Visual visual,
  String name,
  String cat, {
  int lvl = 1,
  String? fact,
}) => SortItem(
  id: id,
  name: name,
  visual: visual,
  categoryId: cat,
  minLevel: lvl,
  fact: fact,
);

GameCategory _c(
  String id,
  String label,
  String emoji,
  Color color, {
  int lvl = 1,
  double scale = 1,
}) => GameCategory(
  id: id,
  label: label,
  icon: EmojiVisual(emoji, scale: scale),
  color: color,
  minLevel: lvl,
);

